  function formatSacredTermsHtml(safeHtml) {
    if (!safeHtml || typeof safeHtml !== 'string') {
      return safeHtml == null ? '' : String(safeHtml);
    }
    var segRe = /(<a\b[^>]*>[\s\S]*?<\/a>|<span\b[^>]*class="[^"]*(?:scholar-link|sacred-[a-z-]+)[^"]*"[^>]*>[\s\S]*?<\/span>|<button\b[^>]*>[\s\S]*?<\/button>|<[^>]+>)/gi;
    var parts = safeHtml.split(segRe);
    for (var i = 0; i < parts.length; i += 2) {
      var seg = parts[i];
      if (!seg) continue;
      SACRED_HIGHLIGHT_RE.lastIndex = 0;
      parts[i] = seg.replace(SACRED_HIGHLIGHT_RE, function (full, pre, term) {
        var cls = 'sacred-term';
        if (term.indexOf('благословит его Аллах') !== -1) cls = 'sacred-salawat';
        else if (term.indexOf('Коран') !== -1 || term.indexOf('Сунн') !== -1 || term.indexOf('Сахих') !== -1) cls = 'sacred-term sacred-scripture';
        return pre + '<span class="' + cls + '">' + term + '</span>';
      });
    }
    return parts.join('');
  }

