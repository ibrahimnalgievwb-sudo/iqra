/* ---------- perLineNumbered ----------
   Dead code v383. Ни разу не вызывается.
   Логика инлайнена в parseAyahs() (storage.js) — там она
   реализована локально внутри map-колбэка, поэтому удаление
   perLineNumbered безопасно. Оставлено как исторический
   артефакт v383 (маркер: «U-утилита для суры/аята с диапазоном»). */
function perLineNumbered(item) {
  if (!item || item.type === 'surah' || !item.number) return false;
  return /^\d+:\d+(?:-\d+)?$/.test(String(item.number));
}

